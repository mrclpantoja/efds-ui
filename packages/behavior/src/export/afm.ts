/**
 * Código WinAnsi de um ponto de código Unicode. Fora do WinAnsi vira `?` (63); controles
 * (tabulação, quebra, DEL) viram espaço.
 */
export function winAnsiCode(codePoint: number): number {
  if (codePoint < 32 || codePoint === 127) return 32;
  if (codePoint < 127) return codePoint;
  if (codePoint >= 0xa0 && codePoint <= 0xff) return codePoint;
  return CP1252_HIGH[codePoint] ?? 63;
}
