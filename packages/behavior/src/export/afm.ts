/**
 * Larguras (1/1000 de em) da Helvetica e da Helvetica-Bold nos códigos da WinAnsiEncoding
 * (CP1252), tiradas das tabelas AFM padrão do PDF. Servem para medir e quebrar o texto sem
 * embutir fonte: as 14 fontes padrão do PDF existem em todo leitor.
 */

type Spec = readonly (readonly [number, number, number])[];

function build(ascii: readonly number[], rest: Spec): Uint16Array {
  const widths = new Uint16Array(256).fill(556);
  ascii.forEach((w, i) => {
    widths[32 + i] = w;
  });
  for (const [from, to, w] of rest) for (let c = from; c <= to; c += 1) widths[c] = w;
  return widths;
}

